"""Generate one random 256-bit BLE pre-shared key and write it into both projects.

Run from the folder that holds Thermostat and BoilerNode:   python gen_ble_key.py
Creates:         Thermostat/include/ble_key.h
                 BoilerNode/include/ble_key.h
Re-running makes a NEW key: both devices must then be reflashed.
"""
import os, secrets, sys

base = os.path.dirname(os.path.abspath(__file__))
projects = [os.path.join(base, "Thermostat"), os.path.join(base, "BoilerNode")]
missing = [p for p in projects if not os.path.isdir(os.path.join(p, "include"))]
if missing:
    sys.exit("Project folder(s) not found next to this script: " + ", ".join(missing))

targets = [os.path.join(p, "include", "ble_key.h") for p in projects]
if any(os.path.exists(t) for t in targets) and "--force" not in sys.argv:
    sys.exit("ble_key.h already exists. Use --force to replace it (both devices need reflashing).")

key = secrets.token_bytes(32)
rows = [", ".join(f"0x{b:02x}" for b in key[i:i + 8]) for i in range(0, 32, 8)]
body = ("// Generated by gen_ble_key.py. Keep private. Must be identical in Thermostat and BoilerNode.\n"
        "#pragma once\n#define BLE_PSK { " + ", \\\n                  ".join(rows) + " }\n")
for t in targets:
    with open(t, "w", newline="\n") as f:
        f.write(body)
    print("wrote", t)
print("Done. Now rebuild and flash BOTH projects.")
